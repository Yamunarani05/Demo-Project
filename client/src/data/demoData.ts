export interface WorkflowStageItem {
  id: string;
  name: string;
  status: 'completed' | 'in_progress' | 'scheduled' | 'pending';
  completedAt?: string;
  assignedTo?: string;
  notes?: string;
}

export interface DemoClient {
  id: string;
  studioId: string;
  serialNumber: string;
  name: string;
  partnerName?: string;
  email: string;
  phone: string;
  eventType: string; // e.g. 'Destination Wedding', 'Royal Heritage Wedding', 'Beachside Celebration', 'Classic Wedding'
  shootType: 'Pre-Wedding' | 'Post-Wedding' | 'Both';
  eventDate: string;
  location: string;
  budget: number;
  paidAmount: number;
  notes?: string;
  created_at: string;
  preWeddingStages: WorkflowStageItem[];
  postWeddingStages: WorkflowStageItem[];
  preWeddingProgress: number; // 0 to 100
  postWeddingProgress: number; // 0 to 100
}

